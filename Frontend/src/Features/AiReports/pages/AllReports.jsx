import { useEffect, useState } from 'react'
import { Link } from 'react-router-dom'
import { useTheme } from '../../../contexts/themeContext.js'
import WorkspaceNavigation from '../../../components/WorkspaceNavigation.jsx'
import ToggleTheme from '../../../components/ToggleTheme/ToggleTheme.jsx'
import { UseAiReport } from '../hook/UseAiReport.js'
import '../styles/interview.report.scss'
import '../styles/all-reports.scss'
import '../../../styles/visual-system.scss'

/**
 * Formats an ISO date string into a user-friendly date format.
 *
 * @param {string|Date} date - Date to format.
 * @returns {string} Formatted date string or fallback.
 */
const formatReportDate = (date) => {
  if (!date) return 'Date unavailable'

  const parsedDate = new Date(date)
  return Number.isNaN(parsedDate.getTime())
    ? 'Date unavailable'
    : parsedDate.toLocaleDateString(undefined, { year: 'numeric', month: 'short', day: 'numeric' })
}

/**
 * Page component displaying a list of all historical interview reports generated by the user.
 *
 * @returns {import('react').JSX.Element}
 */
export default function AllReports() {
  const { theme } = useTheme()
  const { reports, loading, HandleGetAllReports } = UseAiReport()
  const [hasLoaded, setHasLoaded] = useState(false)
  const [error, setError] = useState('')
  const reportItems = reports || []

  useEffect(() => {
    let active = true

    const loadReports = async () => {
      const result = await HandleGetAllReports()
      if (active) {
        setError(result?.success ? '' : result?.message || 'Unable to load reports.')
        setHasLoaded(true)
      }
    }

    loadReports()
    return () => {
      active = false
    }
  }, [HandleGetAllReports])

  return (
    <main className="ir-page ir-all-reports-page" data-theme={theme}>
      <WorkspaceNavigation active="reports" />
      <header className="ir-topbar">
        <div className="ir-topbar-context">
          <span>Library</span>
          <span aria-hidden="true">/</span>
          <strong>All reports</strong>
        </div>
        <div className="ir-topbar-actions">
          <Link className="ir-home-link" to="/#new-assessment">New assessment <span aria-hidden="true">→</span></Link>
          <ToggleTheme />
        </div>
      </header>

      <div className="ir-container">
        <section className="ir-report-header ir-report-header--compact ir-library-header">
          <div className="ir-library-heading">
            <span className="ir-library-heading__icon" aria-hidden="true">
              <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.7" strokeLinecap="round" strokeLinejoin="round">
                <rect x="6" y="4" width="14" height="17" rx="2" />
                <path d="M4 17V6a2 2 0 0 1 2-2m4 5h6m-6 4h6m-6 4h4" />
              </svg>
            </span>
            <div>
              <p className="ir-report-kicker">YOUR WORKSPACE</p>
              <h1>Your interview reports</h1>
              <p className="ir-report-subtitle">Access and review your previous interview analyses.</p>
            </div>
          </div>
          <span className="ir-library-count" aria-live="polite">
            <svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round">
              <rect x="5" y="4" width="14" height="17" rx="2" />
              <path d="M9 4V3h6v1m-6 6h6m-6 4h6" />
            </svg>
            {reportItems.length} saved {reportItems.length === 1 ? 'report' : 'reports'}
          </span>
        </section>

        {error && <p className="ir-empty-state" role="alert">{error}</p>}
        {(loading || !hasLoaded) && <p className="ir-empty-state" role="status">Loading reports...</p>}

        {hasLoaded && !loading && !error && reportItems.length === 0 && (
          <section className="ir-empty-state">
            <h2>No reports yet</h2>
            <p>Generate an interview report and it will appear here.</p>
            <Link className="ir-text-link" to="/">Create a report <span aria-hidden="true">→</span></Link>
          </section>
        )}

        {!error && reportItems.length > 0 && (
          <div className="ir-all-reports-list" aria-label="Saved interview reports">
            {reportItems.map((report) => {
              const score = report.readiness?.OverallScore
              const validScore = typeof score === 'number' && Number.isFinite(score)
              const reportId = String(report._id || '')

              return (
                <Link
                  className="ir-report-list-row"
                  key={reportId}
                  to={`/interview-report/report/${reportId}`}
                  aria-label={`Open interview report ${reportId}`}
                >
                  <span className="ir-report-list-icon" aria-hidden="true">
                    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.7" strokeLinecap="round" strokeLinejoin="round">
                      <path d="m8 8-4 4 4 4m8-8 4 4-4 4m-3-11-2 14" />
                    </svg>
                  </span>
                  <span className="ir-report-list-main">
                    <strong>{report.reportTitle || report.targetRole || report.jobDescription || 'Interview report'}</strong>
                    <small>
                      {report.targetRole ? `Target role: ${report.targetRole}` : 'Interview analysis'}
                      {report.resumeTitle ? ` · Resume: ${report.resumeTitle}` : ''}
                    </small>
                  </span>
                  <span className="ir-report-list-details">
                    <span>
                      <svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.7" strokeLinecap="round" strokeLinejoin="round">
                        <rect x="3.5" y="5" width="17" height="16" rx="2" />
                        <path d="M16 3v4M8 3v4M3.5 10h17" />
                      </svg>
                      {formatReportDate(report.createdAt)}
                    </span>
                    <span>
                      <svg aria-hidden="true" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.7" strokeLinecap="round" strokeLinejoin="round">
                        <path d="M9 3 7 21m10-18-2 18M4 8h16M3 16h16" />
                      </svg>
                      ID {reportId.slice(-8) || 'unavailable'}
                    </span>
                  </span>
                  <span
                    className="ir-report-list-score"
                    role="img"
                    aria-label={validScore ? `Readiness score ${score} out of 100` : 'Readiness score unavailable'}
                    style={{ '--report-score': `${validScore ? Math.min(100, Math.max(0, score)) : 0}%` }}
                  >
                    <strong>{validScore ? score : '—'}</strong>
                    <small>Readiness</small>
                  </span>
                  <span className="ir-report-list-action">
                    View report <span aria-hidden="true">→</span>
                  </span>
                </Link>
              )
            })}
          </div>
        )}
      </div>
    </main>
  )
}
